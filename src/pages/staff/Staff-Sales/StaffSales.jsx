// ==========================================
// EXPORT PDF FUNCTION (Sales Template)
// ==========================================
export const exportSalesToPDF = (salesData, filename = "sales-report.pdf", generatedBy = "Staff") => {
  const doc = new jsPDF();

  const primaryColor = [30, 41, 59];
  const accentColor = [37, 99, 235];
  const lightBg = [248, 250, 252];

  // Header Design
  doc.setFillColor(...accentColor);
  doc.rect(14, 15, 3, 14, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.setTextColor(...primaryColor);
  doc.text("ADRENALINE AQUA WATER REFILLING STATION", 21, 22);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text("Sales Performance & Revenue Report", 21, 28);

  doc.setFontSize(9);
  doc.text(`Generated: ${new Date().toLocaleDateString()}`, 196, 22, { align: "right" });

  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.4);
  doc.line(14, 34, 196, 34);

  // Summary Box inside PDF
  const totalSalesSum = salesData.reduce((sum, item) => {
    // Alisin ang currency symbol at commas kung meron man para makwenta nang tama
    const cleanNum = Number(String(item.totalSales || 0).replace(/[^\d.-]/g, ""));
    return sum + cleanNum;
  }, 0);

  doc.setFillColor(...lightBg);
  doc.roundedRect(14, 40, 182, 14, 1.5, 1.5, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(...primaryColor);
  doc.text(`Total Records: ${salesData.length}`, 18, 49);
  doc.text(`Total Revenue: ₱${totalSalesSum.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`, 110, 49);

  // Table Setup
  const tableColumn = ["Sales ID", "Date", "Total Products", "Payment Method", "Total Sales"];
  const tableRows = salesData.map((item) => [
    item.salesId || "—",
    item.date || "—",
    item.totalProducts ?? 0,
    item.paymentMethod || "—",
    item.totalSales.startsWith("₱") ? item.totalSales : `₱${item.totalSales}`,
  ]);

  autoTable(doc, {
    head: [tableColumn],
    body: tableRows,
    startY: 60,
    theme: "striped",
    headStyles: {
      fillColor: primaryColor,
      textColor: [255, 255, 255],
      fontStyle: "bold",
      fontSize: 8,
      cellPadding: 6,
    },
    bodyStyles: {
      textColor: [51, 65, 85],
      fontSize: 8,
      cellPadding: 6,
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    margin: { left: 14, right: 14 },
    didDrawPage: (data) => {
      const pageHeight = doc.internal.pageSize.height;
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(`Generated by: ${generatedBy}`, data.settings.margin.left, pageHeight - 10);
      doc.text(`Page ${doc.internal.getNumberOfPages()}`, doc.internal.pageSize.width - data.settings.margin.right, pageHeight - 10, { align: "right" });
    },
  });

  doc.save(filename);
};

function StaffSales() {
  const [sales, setSales] = useState([]);
  const [monthlySales, setMonthlySales] = useState([]);
  const [search, setSearch] = useState("");
  const [paymentFilter, setPaymentFilter] = useState("All");

  const [stats, setStats] = useState({
    today: 0,
    weekly: 0,
    monthly: 0,
    overall: 0,
  });

  // ===============================
  // TOAST
  // ===============================
  const [toast, setToast] = useState({
    message: "",
    type: "success",
    show: false,
  });
  const toastTimer = useRef(null);

  const showToast = (message, type = "success") => {
    clearTimeout(toastTimer.current);
    setToast({ message, type, show: true });
    toastTimer.current = setTimeout(() => {
      setToast({ message: "", type: "success", show: false });
    }, 3000);
  };

  useEffect(() => {
    return () => clearTimeout(toastTimer.current);
  }, []);

  // ===============================
  // AUTO-RECORD COMPLETED ORDERS AS SALES
  // Kasama dito ang:
  //   - DELIVERY: delivery_schedule.delivery_status = "Delivered"
  //   - PICKUP:   orders.status = "Picked Up"
  // Lahat ng completed na walang sales record ay lalagyan ng isa.
  // ===============================
  const syncingRef = useRef(false);

  const syncDeliveredToSales = async () => {
    if (syncingRef.current) return; // iwas doble kung sabay ang takbo
    syncingRef.current = true;

    try {
      // 1a. Lahat ng delivered na delivery
      const { data: delivered, error: deliveredError } = await supabase
        .from("delivery_schedule")
        .select("order_id")
        .eq("delivery_status", "Delivered");

      if (deliveredError) {
        console.log("Sync (delivery_schedule) error:", deliveredError.message);
        return;
      }

      // 1b. Lahat ng Pickup order na Picked Up na
      const { data: pickedUp, error: pickedUpError } = await supabase
        .from("orders")
        .select("order_id")
        .eq("order_type", "Pickup")
        .eq("status", "Picked Up");

      if (pickedUpError) {
        console.log("Sync (pickup orders) error:", pickedUpError.message);
        return;
      }

      const completedIds = [
        ...new Set(
          [...(delivered || []), ...(pickedUp || [])]
            .map((d) => d.order_id)
            .filter(Boolean)
        ),
      ];

      if (completedIds.length === 0) return;

      // 2. Mga order na mayroon nang sales record
      const { data: existing, error: existingError } = await supabase
        .from("sales")
        .select("sales_code, order_id");

      if (existingError) {
        console.log("Sync (sales) error:", existingError.message);
        return;
      }

      const existingOrderIds = new Set(
        (existing || []).map((s) => String(s.order_id))
      );

      const missingIds = completedIds.filter(
        (id) => !existingOrderIds.has(String(id))
      );

      if (missingIds.length === 0) return;

      // 3. Detalye ng mga order na kulang ang sales record
      const { data: missingOrders, error: ordersError } = await supabase
        .from("orders")
        .select(`
          order_id,
          total_amount,
          payment_method,
          order_date,
          delivery_date,
          order_items!order_items_order_id_fkey(
            quantity
          )
        `)
        .in("order_id", missingIds);

      if (ordersError) {
        console.log("Sync (orders) error:", ordersError.message);
        return;
      }

      // 4. Susunod na sales code (SAL2026001, SAL2026002, ...)
      const year = new Date().getFullYear();
      const codePattern = new RegExp(`^SAL${year}(\\d+)$`);

      let nextNumber = (existing || []).reduce((max, s) => {
        const match = String(s.sales_code || "").match(codePattern);
        return match ? Math.max(max, Number(match[1])) : max;
      }, 0);

      const newRows = (missingOrders || []).map((order) => {
        nextNumber += 1;

        return {
          sales_code: `SAL${year}${String(nextNumber).padStart(3, "0")}`,
          order_id: order.order_id,
          total_products: (order.order_items || []).reduce(
            (sum, item) => sum + Number(item.quantity || 0),
            0
          ),
          total_sales: Number(order.total_amount || 0),
          payment_method: order.payment_method,
          // Delivery: delivery date. Pickup: walang delivery date kaya order date.
          date: order.delivery_date || order.order_date || new Date(),
        };
      });

      if (newRows.length === 0) return;

      const { error: insertError } = await supabase
        .from("sales")
        .insert(newRows);

      if (insertError) {
        console.log("Sync (insert sales) error:", insertError.message);
      }
    } finally {
      syncingRef.current = false;
    }
  };

  // ===============================
  // LOAD: sync muna, tapos fetch
  // ===============================
  const refreshSales = async () => {
    await syncDeliveredToSales();
    await fetchSales();
  };

  useEffect(() => {
    refreshSales();
  }, []);

  // Kapag may bagong "Delivered" o "Picked Up" habang bukas ang page, mag-update agad.
  // (Kailangang naka-enable ang Realtime sa delivery_schedule at orders.)
  useEffect(() => {
    const channel = supabase
      .channel("staff-sales-delivery-sync")
      .on(
        "postgres_changes",
        { event: "*", schema: "public", table: "delivery_schedule" },
        () => refreshSales()
      )
      .on(
        "postgres_changes",
        { event: "*", schema: "public", table: "orders" },
        () => refreshSales()
      )
      .subscribe();

    return () => {
      supabase.removeChannel(channel);
    };
  }, []);

  const fetchSales = async () => {
    // AUTOMATIC SORTING: pinakabago ang nasa itaas
    // (kung pareho ang petsa, ang mas mataas na sales code ang mauuna)
    const { data, error } = await supabase
      .from("sales")
      .select(`
        sales_code,
        date,
        total_products,
        total_sales,
        payment_method
      `)
      .order("date", { ascending: false })
      .order("sales_code", { ascending: false });

    if (error) {
      console.log(error.message);
      showToast("Failed to load sales: " + error.message, "error");
      return;
    }

    const now = new Date();
    const startOfToday = new Date(now.getFullYear(), now.getMonth(), now.getDate());
    const startOfWeek = new Date(now.getTime() - 7 * 24 * 60 * 60 * 1000);
    const startOfMonth = new Date(now.getFullYear(), now.getMonth(), 1);

    let todaySum = 0;
    let weeklySum = 0;
    let monthlySum = 0;
    let overallSum = 0;

    (data || []).forEach((sale) => {
      const saleAmount = Number(sale.total_sales || 0);
      overallSum += saleAmount;

      if (sale.date) {
        const saleDate = new Date(sale.date);
        if (saleDate >= startOfToday) todaySum += saleAmount;
        if (saleDate >= startOfWeek) weeklySum += saleAmount;
        if (saleDate >= startOfMonth) monthlySum += saleAmount;
      }
    });

    setStats({
      today: todaySum,
      weekly: weeklySum,
      monthly: monthlySum,
      overall: overallSum,
    });

    const formatted = (data || []).map((sale) => {
      return {
        salesId: sale.sales_code,
        date: sale.date ? new Date(sale.date).toLocaleDateString() : "-",
        totalProducts: Number(sale.total_products || 0),
        totalSales: `₱${Number(sale.total_sales || 0).toLocaleString()}`,
        paymentMethod: sale.payment_method || "-",
      };
    });

    setSales(formatted);

    const months = [
      "Jan", "Feb", "Mar", "Apr", "May", "Jun",
      "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
    ];

    const grouped = {};
    months.forEach((month) => {
      grouped[month] = 0;
    });

    (data || []).forEach((sale) => {
      if (!sale.date) return;
      const month = new Date(sale.date).toLocaleString("en-US", {
        month: "short",
      });
      if (grouped[month] !== undefined) {
        grouped[month] += Number(sale.total_sales || 0);
      }
    });

    const graphData = months.map((month) => ({
      month,
      sales: grouped[month],
    }));

    setMonthlySales(graphData);
  };

  const filtered = sales.filter((item) => {
    const matchSearch = item.salesId?.toLowerCase().includes(search.toLowerCase());
    const matchPayment = paymentFilter === "All" || item.paymentMethod === paymentFilter;
    return matchSearch && matchPayment;
  });

  // ===============================
  // EXPORT PDF (with toast)
  // ===============================
  const handleExportPDF = () => {
    if (filtered.length === 0) {
      showToast("No sales records to export.", "error");
      return;
    }

    try {
      const savedUser = JSON.parse(localStorage.getItem("user")) || {};
      const userPosition = savedUser.position || savedUser.role || "Staff";
      const userName = savedUser.name || savedUser.fullName || "Staff";
      const generatedByFull = `${userPosition} - ${userName}`;

      exportSalesToPDF(filtered, "sales-report.pdf", generatedByFull);
      showToast("Sales report exported successfully!", "success");
    } catch (err) {
      console.error("Export error:", err);
      showToast("Failed to export sales report.", "error");
    }
  };

  const columns = [
    { key: "salesId", label: "Sales ID" },
    { key: "date", label: "Date" },
    { key: "totalProducts", label: "Total Products" },
    { key: "totalSales", label: "Total Sales" },
    { key: "paymentMethod", label: "Payment Method" },
  ];

  const lineData = {
    labels: monthlySales.map(item => item.month),
    datasets: [
      {
        label: "Monthly Sales",
        data: monthlySales.map(item => item.sales),
        borderColor: "#2563eb",
        backgroundColor: (context) => {
          const chart = context.chart;
          const { ctx, chartArea } = chart;
          if (!chartArea) return null;
          const gradient = ctx.createLinearGradient(
            0, chartArea.top, 0, chartArea.bottom
          );
          gradient.addColorStop(0, "rgba(37,99,235,.35)");
          gradient.addColorStop(1, "rgba(147,197,253,0)");
          return gradient;
        },
        fill: true,
        tension: 0.35,
        borderWidth: 3,
        pointStyle: "circle",
        pointRadius: 7,
        pointHoverRadius: 10,
        pointBackgroundColor: "#93c5fd",
        pointBorderColor: "#2563eb",
        pointBorderWidth: 2,
        pointHoverBackgroundColor: "#ffffff",
        pointHoverBorderColor: "#2563eb",
        pointHoverBorderWidth: 3,
      },
    ],
  };

  const lineOptions = {
    responsive: true,
    maintainAspectRatio: false,
    interaction: {
      mode: "index",
      intersect: false,
    },
    plugins: {
      legend: {
        display: false,
      },
      tooltip: {
        backgroundColor: "#1e293b",
        titleColor: "#fff",
        bodyColor: "#fff",
        padding: 12,
        cornerRadius: 10,
        callbacks: {
          label: (context) => `₱${Number(context.raw).toLocaleString()}`,
        },
      },
    },
    scales: {
      x: {
        grid: {
          display: false,
        },
        ticks: {
          autoSkip: false,
          maxRotation: 0,
          minRotation: 0,
          font: {
            size: 11,
          },
        },
      },
      y: {
        beginAtZero: true,
        ticks: {
          callback: (value) => `₱${value}`,
        },
      },
    },
  };

  return (
    <div className="staffsales-page">
      {/* TOAST */}
      {toast.show && (
        <div className={`sales-toast ${toast.type}`}>
          <div className="staffsales-toast-icon">
            {toast.type === "success" ? (
              <CheckCircle size={20} />
            ) : (
              <XCircle size={20} />
            )}
          </div>
          <div className="staffsales-toast-text">{toast.message}</div>
        </div>
      )}

      {/* HEADER SECTION */}
      <div className="staffsales-header">
        <div>
          <h1>Sales</h1>
          <p>Monitor daily and monthly sales performance</p>
        </div>
      </div>

      {/* 💳 OVERVIEW CARDS */}
      <div className="staffsales-cards-container">
        <div className="staffsales-card card-today">
          <div className="icon-wrapper">
            <Calendar size={24} />
          </div>
          <div className="staffcard-info">
            <span className="staffcard-label">Today Sales</span>
            <h2 className="staffcard-value">₱{stats.today.toLocaleString()}</h2>
          </div>
        </div>

        <div className="staffsales-card card-weekly">
          <div className="icon-wrapper">
            <BarChart3 size={24} />
          </div>
          <div className="staffcard-info">
            <span className="staffcard-label">Weekly Sales</span>
            <h2 className="staffcard-value">₱{stats.weekly.toLocaleString()}</h2>
          </div>
        </div>

        <div className="staffsales-card card-monthly">
          <div className="icon-wrapper">
            <CalendarDays size={24} />
          </div>
          <div className="staffcard-info">
            <span className="staffcard-label">Monthly Sales</span>
            <h2 className="staffcard-value">₱{stats.monthly.toLocaleString()}</h2>
          </div>
        </div>

        <div className="staffsales-card card-overall">
          <div className="icon-wrapper">
            <PieChart size={24} />
          </div>
          <div className="staffcard-info">
            <span className="staffcard-label">Overall Sales</span>
            <h2 className="staffcard-value">₱{stats.overall.toLocaleString()}</h2>
          </div>
        </div>
      </div>

      {/* CONTROLS SECTION */}
      <div className="staffcontrols-row">
        <input
          type="text"
          className="staffsearch-input"
          placeholder="Search sales ID..."
          value={search}
          onChange={(e) => setSearch(e.target.value)}
        />

        <select
          className="staffpaymentfilter-select"
          value={paymentFilter}
          onChange={(e) => setPaymentFilter(e.target.value)}
        >
          <option value="All">All Payment</option>
          <option value="COD">COD</option>
          <option value="GCash">GCash</option>
        </select>

        <button
          onClick={handleExportPDF}
          className="export-pdf-btn"
          style={{
            display: "flex",
            alignItems: "center",
            gap: "6px",
            padding: "10px 16px",
            cursor: "pointer",
            background: "#334155",
            color: "#fff",
            border: "none",
            borderRadius: "8px",
            fontWeight: "600",
            fontSize: "14px",
            height: "41px"
          }}
        >
          <Download size={16} /> Export PDF
        </button>
      </div>

      {/* DATA TABLE */}
      <div className="stafftable-container">
        <Table columns={columns} data={filtered} emptyMessage="No sales records yet." />
      </div>

      {/* MONTHLY PERFORMANCE GRAPH */}
      <div className="staffsales-bottom">
        <div className="staffsales-graph-card">
          <h3 className="staffgraph-title">Monthly Sales Revenue</h3>

          {monthlySales.length > 0 ? (
            <div style={{ width: "100%", height: "320px" }}>
              <Line data={lineData} options={lineOptions} />
            </div>
          ) : (
            <div className="staffgraph-placeholder">
              No sales yet
            </div>
          )}
        </div>
      </div>
    </div>
  );
}

export default StaffSales;
