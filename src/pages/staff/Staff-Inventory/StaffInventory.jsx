import { useState, useEffect, useRef } from "react";
import "./staff-inventory.css";
import Table from "../../../components/Table";
import { supabase } from "../../../supabase";
import {
  Plus,
  Pencil,
  Trash2,
  AlertTriangle,
  PackageX,
  Layers,
  X,
  Download,
  CheckCircle,
  XCircle,
} from "lucide-react";
import jsPDF from "jspdf";
